const byId = id => document.getElementById(id);
const groupSelect = byId('group-select');
const teamSelect = byId('team-select');
let currentGroup = 0;
let currentTeam = 0;
let storageOK = true;
let graded = false;

function read(key) {
  try { return localStorage.getItem(key) || ''; }
  catch (_) { storageOK = false; return ''; }
}
function write(key, value) {
  try { localStorage.setItem(key, value); return true; }
  catch (_) { storageOK = false; return false; }
}
function storageNotice(saved = false) {
  byId('storage-status').textContent = storageOK
    ? (saved ? 'Черновик сохранён в этом браузере.' : 'Текст в полях сохраняется автоматически.')
    : 'Браузер не позволяет сохранять черновики. Текст доступен до ухода со страницы; сохраните его самостоятельно.';
}
function validNumber(value, max) {
  const n = Number(value);
  return Number.isInteger(n) && n >= 1 && n <= max ? n : 0;
}
function key(field) { return `fl4_${currentGroup}_${currentTeam}_${field}`; }
function draftFields() { return document.querySelectorAll('[data-draft]'); }

function selectContext() {
  currentGroup = validNumber(groupSelect.value, 4);
  currentTeam = validNumber(teamSelect.value, 5);
  const active = !!(currentGroup && currentTeam);
  teamSelect.disabled = !currentGroup;
  byId('next-seminar').href = currentGroup ? `seminar-5.html?group=${currentGroup}` : 'seminar-5.html';
  byId('save-team').disabled = !active;
  byId('context').textContent = active ? `Учебная группа ${currentGroup} · Команда ${currentTeam}` : currentGroup ? `Учебная группа ${currentGroup}. Выберите команду.` : 'Выберите группу, затем команду.';
  draftFields().forEach(field => {
    if (active && field.disabled) {
      // Mount an editable control when a team is selected, including on browsers
      // that retain the initial disabled editing state of a textarea.
      const editable = field.cloneNode(true);
      editable.disabled = false;
      field.replaceWith(editable);
      field = editable;
    }
    field.disabled = !active;
    field.value = active ? read(key(field.dataset.draft)) : '';
  });
  if (active) {
    const task = tasks[currentTeam - 1];
    byId('team-task').innerHTML = `<h3>Команда ${currentTeam}. ${task.title}</h3><p>${task.text}</p><small>${task.output}</small>`;
  } else {
    byId('team-task').textContent = 'Выберите свою группу и команду выше, чтобы получить задание.';
  }
  const assigned = active ? [currentTeam, currentTeam + 5] : [];
  byId('assignment').textContent = active ? `Команда ${currentTeam}: ситуации ${assigned.join(' и ')}. Подготовьте решение и один вопрос для обсуждения.` : 'После выбора команды здесь появятся номера ваших ситуаций.';
  document.querySelectorAll('.case-card').forEach((card, i) => {
    const yours = assigned.includes(i + 1);
    card.classList.toggle('assigned', yours);
    card.querySelector('.case-tag').hidden = !yours;
    card.open = yours;
  });
  storageNotice();
}

byId('all-tasks').innerHTML = tasks.map(t => `<li><b>${t.title}.</b> ${t.text}</li>`).join('');
byId('cases').innerHTML = cases.map((c, i) => `<details class="case-card" id="case-${i + 1}"><summary>${i + 1}. ${c.title}<span class="case-tag" hidden>ВАША СИТУАЦИЯ</span></summary><p>${c.text}</p><details><summary>Ориентир для обсуждения</summary><p>${c.hint}</p></details><label for="case-draft-${i + 1}">Решение ситуации ${i + 1}</label><textarea id="case-draft-${i + 1}" data-draft="case-${i + 1}" rows="5" disabled placeholder="1. Вид отношения\n2. Участники, права и обязанности\n3. Норма\n4. Юридические факты\n5. Вывод"></textarea></details>`).join('');
byId('team-draft').dataset.draft = 'team';
byId('dispute-draft').dataset.draft = 'dispute';

byId('lesson').addEventListener('input', event => {
  const field = event.target;
  if (!field.matches('[data-draft]')) return;
  if (currentGroup && currentTeam) {
    write(key(field.dataset.draft), field.value);
    storageNotice(true);
  }
});
byId('save-team').addEventListener('click', () => {
  if (!currentGroup || !currentTeam) return;
  draftFields().forEach(field => write(key(field.dataset.draft), field.value));
  storageNotice(true);
});

function resetQuiz() {
  byId('quiz-form').reset();
  byId('quiz-result').hidden = true;
  document.querySelectorAll('.feedback').forEach(el => { el.hidden = true; el.textContent = ''; });
  graded = false;
}
groupSelect.addEventListener('change', () => {
  const next = validNumber(groupSelect.value, 4);
  if (next) write('finlaw_group', String(next));
  teamSelect.value = next ? String(validNumber(read(`fl4_team_${next}`), 5)) : '0';
  const url = new URL(location.href);
  if (next) url.searchParams.set('group', String(next)); else url.searchParams.delete('group');
  history.replaceState(null, '', url);
  resetQuiz();
  selectContext();
});
teamSelect.addEventListener('change', () => {
  if (currentGroup) write(`fl4_team_${currentGroup}`, teamSelect.value);
  resetQuiz();
  selectContext();
});

byId('quiz').innerHTML = questions.map((q, i) => `<fieldset id="question-${i}"><legend>${i + 1}. ${q.text}</legend>${q.options.map((option, j) => `<label class="option"><input type="radio" name="q${i}" value="${j}" required><span>${option}</span></label>`).join('')}<div class="feedback" id="feedback-${i}" hidden></div></fieldset>`).join('');
byId('quiz-form').addEventListener('submit', event => {
  event.preventDefault();
  const data = new FormData(event.currentTarget);
  let score = 0;
  questions.forEach((q, i) => {
    const correct = data.get(`q${i}`) === String(q.answer);
    if (correct) score++;
    const box = byId(`feedback-${i}`);
    box.textContent = `${correct ? 'Верно.' : 'Нужно уточнить. Правильный ответ: ' + q.options[q.answer] + '.'} ${q.why}`;
    box.className = `feedback ${correct ? 'correct' : 'incorrect'}`;
    box.hidden = false;
  });
  const result = byId('quiz-result');
  result.textContent = `${score} из ${questions.length}. ${score >= 9 ? 'Тема усвоена уверенно.' : score >= 7 ? 'Хороший результат. Разберите пояснения к ошибкам.' : 'Повторите нормы по вопросам с ошибками и попробуйте ещё раз.'} Покажите результат преподавателю, если это предусмотрено порядком занятия.`;
  result.hidden = false;
  result.focus();
  graded = true;
});
byId('quiz-form').addEventListener('change', () => {
  if (!graded) return;
  byId('quiz-result').hidden = true;
  document.querySelectorAll('.feedback').forEach(el => { el.hidden = true; });
  graded = false;
});
byId('retry').addEventListener('click', () => {
  resetQuiz();
  byId('quiz').querySelector('input').focus();
});

const params = new URLSearchParams(location.search);
const initialGroup = params.has('group') ? validNumber(params.get('group'), 4) : validNumber(read('finlaw_group'), 4);
groupSelect.value = String(initialGroup);
if (initialGroup) {
  write('finlaw_group', String(initialGroup));
  teamSelect.value = String(validNumber(read(`fl4_team_${initialGroup}`), 5));
}
selectContext();
